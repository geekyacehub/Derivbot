'use strict';
const assert=require('node:assert/strict');
const fs=require('node:fs');
const vm=require('node:vm');
const store=new Map([['dbx_token','old-secret'],['dbx_followers','[{"token":"old-fragment"}]']]);
const localStorage={getItem:k=>store.has(k)?store.get(k):null,setItem:(k,v)=>store.set(k,String(v)),removeItem:k=>store.delete(k)};
const tabStore=new Map();
const sessionStorage={getItem:k=>tabStore.has(k)?tabStore.get(k):null,setItem:(k,v)=>tabStore.set(k,String(v)),removeItem:k=>tabStore.delete(k)};
const elements=new Map();
function el(id){if(!elements.has(id))elements.set(id,{value:'',textContent:'',innerHTML:'',style:{},classList:{add(){},remove(){}},appendChild(){}});return elements.get(id);}
const loc={search:'?token1=oauth-secret&acct1=VRTC&cur1=USD&token2=other-secret&keep=ok&sync=legacy',pathname:'/index.html',hash:'#view'};
let replaced='';
const history={replaceState(_a,_b,url){replaced=url;}};
const ctx=vm.createContext({console,URL,URLSearchParams,location:loc,history,localStorage,sessionStorage,document:{getElementById:el,createElement(){return el('created')},addEventListener(){}},window:{confirm:()=>true},setTimeout(){},clearTimeout(){}});
vm.runInContext(fs.readFileSync('app.js','utf8'),ctx);
const run=code=>vm.runInContext(code,ctx);
run('prepareCredentialSession()');
assert.equal(store.has('dbx_token'),false);
assert.equal(store.has('dbx_followers'),false);
assert.equal(run('S.token'),'oauth-secret');
assert.equal(replaced,'/index.html?keep=ok#view');
assert.ok(!replaced.includes('secret'));
// Config export selects only supported fields and omits account credentials.
run("S.bots=normalizeBots([{id:'macd',installed:true},{id:'custom-123',strategy:'custom',name:'My rule',symbol:'R_75',stake:2,blocks:['even','buy_even']}]); S.auto.running=false; exportBotSettings()");
const exported=el('botConfigText').value;
assert.equal(exported.includes('oauth-secret'),false);
assert.equal(exported.includes('dbx_token'),false);
assert.equal(JSON.parse(exported).version,1);
const malicious={version:1,token:'do-not-import',bots:[{id:'custom-777',strategy:'custom',name:'<img>',symbol:'bad',stake:-3,blocks:['even','__proto__','buy_even']},{id:'macd',installed:true},{id:'custom-777',strategy:'custom'}]};
el('botConfigText').value=JSON.stringify(malicious);
run('importBotSettings()');
assert.equal(run("S.bots.filter(b=>b.id==='custom-777').length"),1);
assert.equal(run("S.bots.find(b=>b.id==='custom-777').symbol"),'R_75');
assert.equal(run("S.bots.find(b=>b.id==='custom-777').stake"),1);
assert.equal(run("S.bots.find(b=>b.id==='custom-777').blocks.length"),2);
assert.equal(store.get('dbx_bots').includes('do-not-import'),false);
assert.equal(run('S.token'),'oauth-secret');
const before=store.get('dbx_bots');
ctx.window.confirm=()=>false;el('botConfigText').value=JSON.stringify({version:1,bots:[]});run('importBotSettings()');
assert.equal(store.get('dbx_bots'),before,'declined import must not replace settings');
ctx.window.confirm=()=>true;
run("S.token='memory-token'; S.ws=null; disconnectDeriv({preserveToken:true})");
assert.equal(run('S.token'),'memory-token');
run('disconnectDeriv()');
assert.equal(run('S.token'),'');
assert.equal(el('tokenInput').value,'');
assert.equal(store.has('dbx_token'),false);
// Stored journal fields and alert text must never be interpreted as HTML.
run(`S.journal=[{time:'<img src=x onerror=alert(1)>',type:'<script>',symbol:'<svg>',stake:1,entry:1,exit:2,digit:'<b>',win:true,profit:1}]; renderJournal(); addAlert('<img src=x onerror=alert(1)>')`);
assert.ok(!el('journalTable').innerHTML.includes('<script>'));
assert.ok(el('journalTable').innerHTML.includes('&lt;script&gt;'));
assert.ok(!el('alertsList').innerHTML.includes('<img'));
run(`S.connected=true; S.currency='<img>'; renderSession()`);
assert.ok(!el('sessionStats').innerHTML.includes('<img'));
assert.equal(run(`csvCell('=1+1')`), `"'=1+1"`);
assert.equal(run(`csvCell(' \t@cmd')`), `"' \t@cmd"`);
assert.equal(run(`csvCell('a,"b"')`), `"a,""b"""`);
assert.equal(run(`csvCell(-5)`), `"-5"`);
// Reconnect is opt-in, only after authorization, tab-scoped and cleared on disconnect.
el('rememberTab').checked=false;
run("S.connected=true; S.token='tab-secret'; S.isDemo=true; saveTabConnection()");
assert.equal(tabStore.size,0);
el('rememberTab').checked=true;
run('S.connected=false; saveTabConnection()');
assert.equal(tabStore.size,0, 'do not persist an unauthenticated token');
run('S.connected=true; saveTabConnection()');
assert.equal(JSON.parse(tabStore.get('dbx_tab_connection')).token,'tab-secret');
run("S.token=''; S.isDemo=false; restoreTabConnection()");
assert.equal(run('S.token'),'tab-secret');
assert.equal(run('S.isDemo'),true);
assert.equal(el('rememberTab').checked,true);
run('disconnectDeriv()');
assert.equal(tabStore.size,0);
assert.equal(run('S.token'),'');
tabStore.set('dbx_tab_connection','not-json');
run('restoreTabConnection()');
assert.equal(tabStore.size,0);
console.log('Credential cleanup, safe rendering and bot settings transfer checks passed');
(async()=>{
  ctx.fetch=async()=>({ok:false});
  ctx.WebSocket=class { constructor(){this.readyState=0;} close(){this.readyState=3;} };
  el('appIdInput').value='1089';el('tokenInput').value='entered-secret';
  await run('connectDeriv()');
  assert.equal(run('S.token'),'entered-secret');
  assert.equal(el('tokenInput').value,'');
  assert.equal(store.has('dbx_token'),false,'connecting must not persist the token');
  run('disconnectDeriv()');
  assert.equal(run('S.token'),'');
  console.log('In-memory connection token checks passed');
})().catch(err=>{console.error(err);process.exitCode=1});
